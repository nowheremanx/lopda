    for (i = 0; i < 44; i++) {
      seed = (seed * 1103515245 + 12345) & 0x7fffffff;
      x = seed % W;
      seed = (seed * 1103515245 + 12345) & 0x7fffffff;
      y = 3 + (seed >> 5) % 86;
      put(px, x, y, i % 9 === 0 ? 0 : i % 4 === 0 ? 1 : 2);
    }
    /* the moon, low on the right: a paper disc with darker seas */
    disc(px, 166, 48, 13, 1);
    disc(px, 166, 48, 11, 0);
    disc(px, 162, 45, 2, 1);
    disc(px, 170, 53, 3, 1);
    put(px, 171, 52, 0);
    put(px, 161, 44, 0);
