  function grid(rows) {
    var h = rows.length, w = 0;
    for (var r = 0; r < h; r++) w = Math.max(w, rows[r].length);   /* short rows are padded with clear */
    var px = new Uint8Array(w * h);
    for (var y = 0; y < h; y++) for (var x = 0; x < w; x++) {
      var c = rows[y].charAt(x);
      px[y * w + x] = c === "." || c === "" ? 255 : (c.charCodeAt(0) - 48) & 3;
    }
    return { w: w, h: h, px: px };
  }
  function blank(w, h, t) { var px = new Uint8Array(w * h); px.fill(t == null ? 255 : t); return { w: w, h: h, px: px }; }
  function set(s, x, y, t) { if (x >= 0 && y >= 0 && x < s.w && y < s.h) s.px[y * s.w + x] = t; }
  function copy(s) { return { w: s.w, h: s.h, px: new Uint8Array(s.px) }; }
