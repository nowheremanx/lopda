/* ---- state, saved with game.save ---- */
var S, busy = false;
function fresh() { return { place: "yard", tx: 12, ty: 12, pets: 0, found: false, key: false, thanked: false }; }
function save() { game.save("state", S); }

/* ---- a person who walks one tile at a time on a map ---- */
var DIRS = { up: [0, -1], down: [0, 1], left: [-1, 0], right: [1, 0] };
function walker(tx, ty, dir) { return { tx: tx, ty: ty, x: tx * TILE, y: ty * TILE, dir: dir || "down", step: 0, from: null }; }
function cameraFor(p, map) { return LoGame.camera(p.x + TILE / 2, p.y + TILE / 2, 160, VIEW_H, map.width, map.height); }

/* one scene definition shared by both places; each place says what is in it */
function place(map, things) {
  var p;
  return {
    enter: function (spawn) { p = walker(spawn.tx, spawn.ty, spawn.dir); S.place = spawn.place; S.tx = p.tx; S.ty = p.ty; },
    update: function (dt) {
      if (things.update) things.update(dt);
      if (busy) return;
      if (p.from) {                                   /* sliding one tile */
        p.step = Math.min(1, p.step + dt / 0.15);
        p.x = LoGame.lerp(p.from[0], p.tx * TILE, p.step); p.y = LoGame.lerp(p.from[1], p.ty * TILE, p.step);
        if (p.step >= 1) {                            /* arrived: doors and things on the ground trigger here */
          p.from = null; S.tx = p.tx; S.ty = p.ty;
          if (map.get(p.tx, p.ty) === "D") things.door();
          else if (things.step) things.step(p.tx, p.ty);
        }
        return;
      }
      var want = null;
      ["up", "down", "left", "right"].forEach(function (d) { if (game.btn(d)) want = d; });
      if (!want && game.pointer.down) {               /* touch: walk toward the finger */
        var cam = cameraFor(p, map);
        var dx = game.pointer.x + cam.x - (p.x + TILE / 2), dy = game.pointer.y - HUD + cam.y - (p.y + TILE / 2);
        if (Math.abs(dx) > 12 || Math.abs(dy) > 12) want = Math.abs(dx) > Math.abs(dy) ? (dx > 0 ? "right" : "left") : (dy > 0 ? "down" : "up");
        else if (game.pointer.pressed) act();
      }
      if (want) {
        p.dir = want;
        var nx = p.tx + DIRS[want][0], ny = p.ty + DIRS[want][1];
        if (!map.solid(nx, ny) && !things.blocked(nx, ny)) { p.from = [p.x, p.y]; p.tx = nx; p.ty = ny; p.step = 0; }
      }
      if (game.pressed("a")) act();
      if (game.pressed("start")) menu();
      /* A works on what you face, or on what you stand on */
      function act() { things.act(p.tx + DIRS[p.dir][0], p.ty + DIRS[p.dir][1], p); }
    },
    draw: function (g) {
      var cam = cameraFor(p, map);
      g.clear(g.INK);
      g.origin(0, HUD); g.clip(0, 0, 160, VIEW_H);    /* the map lives under the status bar */
      map.draw(g, cam.x, cam.y);
      g.origin(-cam.x, HUD - cam.y);                  /* from here on, draw in map pixels */
      things.draw(g, p);
      var walking = p.from && Math.floor(p.step * 2) % 2 === 0;
      var s = p.dir === "up" ? (walking ? ART.up2 : ART.up) : p.dir === "down" ? (walking ? ART.down2 : ART.down) : (walking ? ART.side2 : ART.side);
      g.sprite(s, p.x, p.y, { flip: p.dir === "left" });
      g.origin(0, 0); g.clip();
      g.window(0, 0, 160, HUD, { thin: true });
      g.text(T({ zh: "摸猫 {n}  钥匙 {k}", en: "Pets {n}  Key {k}" }, { n: S.pets, k: S.key ? T({ zh: "有", en: "yes" }) : T({ zh: "无", en: "no" }) }), 4, 1);
    }
  };
}

/* ---- the yard ---- */
var cat = { tx: 11, ty: 5 }, KEY = { tx: 3, ty: 16 };
var catPetUntil = 0;
async function pickKey() {
  busy = true;
  S.found = true; S.key = true; own(SFX_KEY, "ok"); game.flash();
  await game.say(T({ zh: "草丛里有一把旧钥匙。你把它收好了。", en: "An old key in the grass. You pocket it." })); save();
  busy = false;
}
game.scene("yard", place(YARD, {
  update: function () {
    YARD_TILES["~"] = Math.floor(game.time / 0.5) % 2 ? ART.water2 : ART.water;
    YARD_TILES["*"] = Math.floor(game.time / 0.8) % 2 ? ART.flower2 : ART.flower;
  },
  blocked: function (x, y) { return x === cat.tx && y === cat.ty; },
  door: function () { game.sfx("move"); game.go("house", { place: "house", tx: 5, ty: 6, dir: "up" }); },
  draw: function (g, p) {
    if (!S.found) {
      g.sprite(ART.key, KEY.tx * TILE, KEY.ty * TILE);
      if (Math.floor(game.time / 1.2) % 2 === 0) g.pixel(KEY.tx * TILE + 12, KEY.ty * TILE + 3, g.PAPER);
    }
    var catFrame = game.time < catPetUntil || Math.floor(game.time / 0.6) % 2;
    g.sprite(catFrame ? ART.cat2 : ART.cat, cat.tx * TILE, cat.ty * TILE, { flip: p.x > cat.tx * TILE });
  },
  step: function (x, y) { if (!S.found && x === KEY.tx && y === KEY.ty) pickKey(); },
  act: async function (x, y, p) {
    if (!S.found && ((x === KEY.tx && y === KEY.ty) || (p.tx === KEY.tx && p.ty === KEY.ty))) return pickKey();
    busy = true;
    if (x === cat.tx && y === cat.ty) {
      await game.say([T({ zh: "喵。", en: "Mew." }), T({ zh: "一只橘猫趴在小路上，眯着眼看你。", en: "A ginger cat lies on the path, squinting at you." })], { name: T({ zh: "猫", en: "Cat" }) });
      var i = await game.choose([T({ zh: "摸摸它", en: "Pet it" }), T({ zh: "走开", en: "Leave" })]);
      if (i === 0) { catPetUntil = game.time + 1; S.pets++; own(SFX_PURR, "coin"); await game.say(T({ zh: "它呼噜呼噜地蹭你的手。", en: "It purrs and rubs your hand." })); save(); }
    }
    busy = false;
  }
}));

/* ---- inside the house ---- */
var elder = { tx: 8, ty: 3 }, ELDER = T({ zh: "老伯", en: "Old man" });
game.scene("house", place(HOUSE, {
  blocked: function (x, y) { return x === elder.tx && y === elder.ty; },
  door: function () { game.sfx("move"); game.go("yard", { place: "yard", tx: 18, ty: 4, dir: "down" }); },
  draw: function (g) {
    var bob = Math.floor(game.time) % 2;
    g.sprite(bob ? ART.elder2 : ART.elder, elder.tx * TILE, elder.ty * TILE + bob);
  },
  act: async function (x, y) {
    if (x !== elder.tx || y !== elder.ty) return;
    busy = true;
    if (S.thanked) await game.say(T({ zh: "猫又胖了。", en: "That cat's got fatter." }), { name: ELDER });
    else if (S.key) {
      S.thanked = true; S.key = false; game.sfx("win");
      await game.say([T({ zh: "这是……我的钥匙！", en: "Why... that's my key!" }), T({ zh: "找了好几天，谢谢你。", en: "Looked for days. Thank you." })], { name: ELDER }); save();
    } else await game.say([T({ zh: "我的钥匙不见了。", en: "I've lost my key." }), T({ zh: "大概掉在院子西南边的草丛里。", en: "Somewhere in the grass, southwest of the yard." })], { name: ELDER });
    busy = false;
  }
}));

/* ---- title and menu ---- */
game.scene("title", {
  enter: function () {
    music();   /* before the first touch or key the runtime holds it, then starts it */
    game.load("state").then(function (v) {
      if (v && v.found == null) v.found = !!(v.key || v.thanked);   /* saves from v1.1.0 */
      S = v;
    });
  },
  update: function () {
    if (!game.ok() || busy) return;
    busy = true;
    game.choose(S ? [T({ zh: "继续", en: "Continue" }), T({ zh: "从头开始", en: "New game" })] : [T({ zh: "开始", en: "Start" })], { cancel: false }).then(function (i) {
      busy = false;
      if (!S || i === 1) S = fresh();
      game.go(S.place, { place: S.place, tx: S.tx, ty: S.ty });
    });
  },
  draw: function (g) {
    g.clear(g.PAPER);
    g.window(20, 30, 120, 44);
    g.text(T({ zh: "小  院", en: "THE YARD" }), 80, 38, { align: "center" });
    g.text(T({ zh: "lo-game 示例", en: "lo-game example" }), 80, 54, { align: "center", color: g.DARK });
    if (Math.floor(game.time * 2) % 2 === 0) g.text(T({ zh: "按 A 开始", en: "PRESS A" }), 80, 100, { align: "center" });
  }
});
async function menu() {
  busy = true;
  var i = await game.choose([T({ zh: "存档", en: "Save" }), T({ zh: "回标题", en: "Title" })], { title: T({ zh: "菜单", en: "Menu" }) });
  if (i === 0) { save(); game.sfx("ok"); await game.say(T({ zh: "存好了。", en: "Saved." })); }
  busy = false;
  if (i === 1) { save(); game.go("title"); }
}

game.start("title");
