(function(){
"use strict";
var lines = [
'<!doctype html>',
'<html><head><meta charset="utf-8">',
'<meta name="viewport" content="width=device-width,initial-scale=1">',
'<title>番茄钟</title>',
'<style>',
':root{--ink:#1f2a14;--dark:#4a5a32;--mid:#7d8a58;--paper:#a3ad7e}',
'*{box-sizing:border-box;touch-action:manipulation}',
'html,body{margin:0;height:100%;overflow:hidden;background:var(--paper);color:var(--ink);font-family:monospace}',
'body{display:flex;flex-direction:column}',
'header{flex:none;padding:6px 10px;border-bottom:2px solid var(--ink);display:flex;align-items:center;gap:8px}',
'header b{font-size:16px;font-weight:400;flex:1}',
'header small{font-size:12px;color:var(--dark)}',
'main{flex:1;min-height:0;overflow-y:auto;padding:10px;display:flex;flex-direction:column;gap:10px}',
'.time{font-size:56px;line-height:1;text-align:center;letter-spacing:1px;margin:6px 0}',
'.mode{text-align:center;font-size:15px}',
'.rounds{display:flex;justify-content:center;gap:6px}',
'.rounds i{width:12px;height:12px;border:2px solid var(--ink);display:block}',
'.rounds i.on{background:var(--ink)}',
'.stats{display:flex;justify-content:space-between;border-top:2px solid var(--ink);border-bottom:2px solid var(--ink);padding:6px 4px;font-size:13px;color:var(--dark)}',
'.row{display:flex;gap:8px}',
'button{font-family:monospace;font-size:16px;min-height:44px;border:2px solid var(--ink);background:var(--paper);color:var(--ink);cursor:pointer;flex:1}',
'button.main{background:var(--ink);color:var(--paper);border-color:var(--ink)}',
'#settings{display:none;position:fixed;inset:0;z-index:2;background:var(--paper);padding:12px;flex-direction:column;gap:8px}',
'#settings.on{display:flex}',
'#settings label{display:flex;align-items:center;justify-content:space-between;font-size:14px;border-bottom:1px dashed var(--dark);padding:5px 0}',
'#settings input{width:64px;font:16px monospace;color:var(--ink);background:var(--paper);border:2px solid var(--ink);padding:4px}',
'.hint{font-size:13px;color:var(--dark);margin:0;line-height:1.35}',
'</style></head>',
'<body>',
'<header><b>番茄钟</b><small>A 开始/暂停 · B 重置 · START 设置</small></header>',
'<main>',
'  <div class="time" id="time">25:00</div>',
'  <div class="mode" id="mode">专注 · 第 1 轮</div>',
'  <div class="rounds" id="rounds"></div>',
'  <div class="row"><button id="go" class="main">开始</button><button id="reset">重置</button></div>',
'  <button id="set">设置</button>',
'  <div class="stats"><span id="today">今天 0 个</span><span id="mins">0 分钟</span></div>',
'  <p class="hint" id="last">完成一个番茄，记录会留在这台机器上。</p>',
'</main>',
'<div id="settings">',
'  <b>设置</b>',
'  <label>专注<input id="work" type="number" min="1" max="120" value="25"></label>',
'  <label>短休息<input id="short" type="number" min="1" max="60" value="5"></label>',
'  <label>长休息<input id="long" type="number" min="1" max="60" value="15"></label>',
'  <label>每几轮长休息<input id="roundsN" type="number" min="1" max="12" value="4"></label>',
'  <div class="row"><button id="save">保存</button><button id="close">取消</button></div>',
'  <p class="hint">只使用本机存档，不联网。</p>',
'</div>',
'<script>',
'(function(){',
'"use strict";',
'var D={settings:{v:1,work:25,short:5,long:15,rounds:4},sessions:[]};',
'var mode="work", left=25*60000, running=false, startedAt=0, leftAtStart=0, round=1, done=0;',
'function $(id){return document.getElementById(id);}',
'function pad(n){return (n<10?"0":"")+n;}',
'function fmt(ms){var s=Math.max(0,Math.ceil(ms/1000));return pad(Math.floor(s/60))+":"+pad(s%60);}',
'function duration(kind){if(kind==="work")return D.settings.work*60000;if(kind==="long")return D.settings.long*60000;return D.settings.short*60000;}',
'function modeName(kind){return kind==="work"?"专注":kind==="long"?"长休息":"短休息";}',
'function persist(){PAD.save("settings",D.settings);PAD.save("timer",{v:1,mode:mode,left:left,running:running,startedAt:startedAt,leftAtStart:leftAtStart,round:round,done:done});PAD.save("sessions",D.sessions.slice(-500));}',
'function todayStats(){',
'  var key=new Date().toDateString(), n=0, mins=0;',
'  D.sessions.forEach(function(s){if(new Date(s.end).toDateString()===key){n++;mins+=s.minutes;}});',
'  return {n:n,mins:mins};',
'}',
'function render(){',
'  $("time").textContent=fmt(left);',
'  $("mode").textContent=modeName(mode)+" · 第 "+round+" 轮";',
'  $("go").textContent=running?"暂停":"开始";',
'  var box=$("rounds");box.textContent="";',
'  for(var i=0;i<D.settings.rounds;i++){var d=document.createElement("i");if(i<(done%D.settings.rounds))d.className="on";box.appendChild(d);}',
'  var st=todayStats();$("today").textContent="今天 "+st.n+" 个";$("mins").textContent=st.mins+" 分钟";',
'  var last=D.sessions[D.sessions.length-1];',
'  $("last").textContent=last?("上次完成 "+new Date(last.end).toLocaleTimeString().slice(0,5)+" · "+last.minutes+" 分钟"):"完成一个番茄，记录会留在这台机器上。";',
'}',
'function start(){',
'  if(running){left=Math.max(0,leftAtStart-(Date.now()-startedAt));running=false;PAD.sfx("tick");persist();render();return;}',
'  running=true;startedAt=Date.now();leftAtStart=left;PAD.sfx("ok");persist();render();',
'}',
'function reset(){running=false;startedAt=0;leftAtStart=0;left=duration(mode);PAD.sfx("tick");persist();render();}',
'function complete(){',
'  running=false;',
'  var now=Date.now();',
'  if(mode==="work"){',
'    D.sessions.push({start:now-duration("work"),end:now,minutes:D.settings.work,kind:"work"});if(D.sessions.length>500)D.sessions=D.sessions.slice(-500);',
'    done++;PAD.sfx("win");',
'    mode=(done%D.settings.rounds===0)?"long":"short";',
'  }else{',
'    PAD.sfx("ok");mode="work";round++;',
'  }',
'  startedAt=0;leftAtStart=0;left=duration(mode);persist();render();',
'}',
'function tick(){',
'  if(!running)return;',
'  left=Math.max(0,leftAtStart-(Date.now()-startedAt));',
'  if(left<=0)complete();else render();',
'}',
'function openSettings(){',
'  $("work").value=D.settings.work;$("short").value=D.settings.short;$("long").value=D.settings.long;$("roundsN").value=D.settings.rounds;',
'  $("settings").className="on";',
'}',
'function closeSettings(){$("settings").className="";}',
'function saveSettings(){',
'  function num(id,lo,hi,def){var v=parseInt($(id).value,10);return isNaN(v)||v<lo||v>hi?def:v;}',
'  D.settings.work=num("work",1,120,25);D.settings.short=num("short",1,60,5);D.settings.long=num("long",1,60,15);D.settings.rounds=num("roundsN",1,12,4);',
'  if(!running){left=duration(mode);}',
'  persist();closeSettings();render();PAD.sfx("ok");',
'}',
'function load(){',
'  PAD.load("settings").then(function(v){if(v&&v.v===1)D.settings=v;return PAD.load("timer");}).then(function(v){',
'    if(v&&v.v===1){mode=v.mode||"work";left=v.left||duration(mode);running=!!v.running;startedAt=v.startedAt||0;leftAtStart=v.leftAtStart||left;round=v.round||1;done=v.done||0;}',
'    return PAD.load("sessions");',
'  }).then(function(v){',
'    if(v&&v.length)D.sessions=v;',
'    if(running&&startedAt)left=Math.max(0,leftAtStart-(Date.now()-startedAt));',
'    render();',
'  }).catch(function(){render();});',
'}',
'$("go").onclick=start;',
'$("reset").onclick=reset;',
'$("set").onclick=openSettings;',
'$("save").onclick=saveSettings;',
'$("close").onclick=closeSettings;',
'PAD.on("press",function(b){if(b==="a")start();else if(b==="b")reset();else if(b==="start")openSettings();});',
'window.setInterval(tick,250);',
'load();',
'})();',
'</script>',
'</body></html>'
];
window.LopdaScriptTemplates = { pomodoro: lines.join("\n") };
})();
