#!/usr/bin/env node
/*
 * Builds the three background plates for 山脚小馆 and writes src/25-plates.js.
 *
 *   node tools/art-shanjiao.mjs
 *
 * The scenes are drawn at exactly 216 x 240 in tools/art-shanjiao-scene.js with
 * the four palette colours only.  This driver maps every pixel to 0-3, packs
 * the result as 2-bit RLE (one byte per run: 6 bits of length, 2 bits of tone),
 * writes the game's PLATES table, and drops PNG previews in drafts/plates/.
 *
 * Needs Playwright for the canvas; the game itself does not.  The generated
 * file is committed, so a normal build does not run this.
 */
import { chromium } from "playwright";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const APP = join(ROOT, "registry/apps/shanjiao-diner");
const PALETTE = [[0x1f, 0x2a, 0x14], [0x4a, 0x5a, 0x32], [0x7d, 0x8a, 0x58], [0xa3, 0xad, 0x7e]];
const NAMES = ["roomDay", "roomNight", "mountain"];

function toneOf(r, g, b) {
  let best = 0, bestD = Infinity;
  for (let i = 0; i < PALETTE.length; i++) {
    const p = PALETTE[i];
    const d = (r - p[0]) ** 2 + (g - p[1]) ** 2 + (b - p[2]) ** 2;
    if (d < bestD) { best = i; bestD = d; }
  }
  return best;
}

function encode(tones) {
  const bytes = [];
  let run = 0, prev = -1;
  for (const v of tones) {
    if (v === prev && run < 64) run++;
    else {
      if (run > 0) bytes.push(((run - 1) << 2) | prev);
      prev = v; run = 1;
    }
  }
  if (run > 0) bytes.push(((run - 1) << 2) | prev);
  return Buffer.from(bytes).toString("base64");
}

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<!doctype html><canvas id="c" width="216" height="240"></canvas>');
await page.addScriptTag({ content: readFileSync(join(ROOT, "tools/art-shanjiao-scene.js"), "utf8") });

mkdirSync(join(ROOT, "drafts/plates"), { recursive: true });
const out = [];
for (const name of NAMES) {
  const plate = await page.evaluate((n) => window.PLATE.draw(n), name);
  const tones = new Uint8Array(plate.w * plate.h);
  let off = 0;
  for (let i = 0; i < tones.length; i++) {
    const r = plate.data[i * 4], g = plate.data[i * 4 + 1], b = plate.data[i * 4 + 2], a = plate.data[i * 4 + 3];
    if (a < 128) { tones[i] = 3; continue; }
    tones[i] = toneOf(r, g, b);
    if (tones[i] !== 0 && tones[i] !== 1 && tones[i] !== 2 && tones[i] !== 3) off++;
  }
  const runs = encode(tones);
  const bytes = Buffer.from(runs, "base64").length;
  const png = await page.evaluate(() => document.getElementById("c").toDataURL("image/png"));
  writeFileSync(join(ROOT, "drafts/plates", name + ".png"), Buffer.from(png.split(",")[1], "base64"));
  out.push({ name, w: plate.w, h: plate.h, runs, bytes });
  console.log(`${name}: ${plate.w}x${plate.h}, ${bytes} B packed, ${(bytes / 1024).toFixed(1)} KB, ${off} off-palette`);
}
await browser.close();

const body = out.map((p) => `  ${p.name}: { w: ${p.w}, h: ${p.h}, runs: "${p.runs}" }`).join(",\n");
const js = `/* Generated by tools/art-shanjiao.mjs from tools/art-shanjiao-scene.js.
 * Three 216 x 240 four-tone plates, 2-bit RLE: one byte per run,
 * 6 bits of length (1-64) and 2 bits of tone.  Do not edit by hand.
 */
var PLATES = {
${body}
};

/* decode a plate once, then draw it like any other lo-game sprite */
function plateSprite(p) {
  if (p._sprite) return p._sprite;
  var bin = atob(p.runs), px = new Uint8Array(p.w * p.h), o = 0;
  for (var i = 0; i < bin.length; i++) {
    var b = bin.charCodeAt(i), n = (b >> 2) + 1, v = b & 3;
    for (var k = 0; k < n; k++) px[o++] = v;
  }
  p._sprite = { w: p.w, h: p.h, px: px };
  return p._sprite;
}
ART.plate = function (g, p, x, y) {
  g.sprite(plateSprite(p), x || 0, y || 0);
};
`;
writeFileSync(join(APP, "src/25-plates.js"), js);
console.log(`wrote ${join(APP, "src/25-plates.js")} (${Buffer.byteLength(js)} B)`);
